// gen_expanse.mjs — generate worlds/expanse.h, the reusable runtime-growth pool.
// Run: node worlds/gen_expanse.mjs   (writes worlds/expanse.h)
// Pool sizes are configurable here; regenerate + recompile after changing them.
import { writeFileSync } from 'fs';

// Z-machine arrays cap at 32767 bytes each, and total dynamic memory is finite,
// so pools are kept modest. Object descriptions use a smaller buffer than rooms.
const ROOMS = 48;
const OBJS = 96;
const NBUF = 32;    // name buffer bytes (byte 0 = length)
const RDBUF = 200;  // room description buffer bytes
const ODBUF = 120;  // object description buffer bytes

const rooms = Array.from({ length: ROOMS }, (_, i) =>
    `BlankRoom xroom_${i} with slot ${i};`).join('\n');
const objs = Array.from({ length: OBJS }, (_, i) =>
    `BlankObject xobj_${i} with slot ${i};`).join('\n');

const h = `! expanse.h — reusable pool for runtime-grown worlds (Path A). CC0.
! GENERATED by gen_expanse.mjs — do not edit by hand; change the generator.
! Include AFTER VerbLib and BEFORE Grammar in the host .inf.
! The proven spike pattern (byte-buffer names matched by parse_name) scaled to a
! flat pool: every blank carries a 'slot' index into shared buffer arrays.

Constant XP_NBUF = ${NBUF};
Constant XP_RDBUF = ${RDBUF};
Constant XP_ODBUF = ${ODBUF};
Constant XP_ROOMS = ${ROOMS};
Constant XP_OBJS = ${OBJS};

Array XP_RoomName -> XP_ROOMS * XP_NBUF;
Array XP_RoomDesc -> XP_ROOMS * XP_RDBUF;
Array XP_ObjName  -> XP_OBJS * XP_NBUF;
Array XP_ObjDesc  -> XP_OBJS * XP_ODBUF;

Global XP_lastroom = 0;
Global XP_lastobj  = 0;

! --- buffer address helpers ---
[ XP_RNm o; return XP_RoomName + o.slot * XP_NBUF; ];
[ XP_RDs o; return XP_RoomDesc + o.slot * XP_RDBUF; ];
[ XP_ONm o; return XP_ObjName  + o.slot * XP_NBUF; ];
[ XP_ODs o; return XP_ObjDesc  + o.slot * XP_ODBUF; ];

! --- shared text helpers (proven in the spike) ---
[ XP_PrintBuf arr i len; len = arr->0; for (i=1:i<=len:i++) print (char) arr->i; ];
[ XP_CopyWord wx arr cap   ad ln i;
   ad = WordAddress(wx); ln = WordLength(wx); if (ln > cap-1) ln = cap-1;
   arr->0 = ln; for (i=0:i<ln:i++) arr->(i+1) = ad->i; ];
[ XP_WordEq wx arr   ad ln i;
   ad = WordAddress(wx); ln = WordLength(wx);
   if (ln ~= arr->0) rfalse;
   for (i=0:i<ln:i++) if (ad->i ~= arr->(i+1)) rfalse; rtrue; ];
! Copy the tail (words wstart..num_words), space-joined, into a buffer.
[ XP_CopyTail wstart arr cap   w ad ln i p;
   p = 0;
   for (w=wstart : w<=num_words : w++) {
      if (p > 0 && p < cap-1) { arr->(p+1) = ' '; p++; }
      ad = WordAddress(w); ln = WordLength(w);
      for (i=0 : i<ln && p<cap-1 : i++) { arr->(p+1) = ad->i; p++; }
   }
   arr->0 = p;
];
! Direction code from the first letter of word wx (n/s/e/w/u/d, full or abbrev).
[ XP_DirCode wx   ad;
   ad = WordAddress(wx);
   switch (ad->0) {
      'n': return 1; 's': return 2; 'e': return 3;
      'w': return 4; 'u': return 5; 'd': return 6;
   }
   return 0;
];
[ XP_TakeFlag wx   ad; ad = WordAddress(wx); if (ad->0 == '1') rtrue; rfalse; ];

! --- classes ---
Class BlankRoom
  with slot 0,
       n_to 0, s_to 0, e_to 0, w_to 0, u_to 0, d_to 0,
       used false,
       short_name [; if ((XP_RNm(self))->0 == 0) print "somewhere"; else XP_PrintBuf(XP_RNm(self)); rtrue; ],
       description [; if ((XP_RDs(self))->0 == 0) "An undefined space."; XP_PrintBuf(XP_RDs(self)); new_line; rtrue; ],
       parse_name [ c; c=0; while (wn <= num_words && XP_WordEq(wn, XP_RNm(self))) { wn++; c++; } return c; ],
  has light;

Class BlankObject
  with slot 0,
       used false,
       takeable true,
       short_name [; if ((XP_ONm(self))->0 == 0) print "thing"; else XP_PrintBuf(XP_ONm(self)); rtrue; ],
       description [; if ((XP_ODs(self))->0 == 0) "Nothing special."; XP_PrintBuf(XP_ODs(self)); new_line; rtrue; ],
       parse_name [ c; c=0; while (wn <= num_words && XP_WordEq(wn, XP_ONm(self))) { wn++; c++; } return c; ],
       before [; Take: if (self.takeable == false) "That is fixed in place."; ],
  has ;

! --- pool instances (generated) ---
${rooms}

${objs}

! --- free-slot finders ---
[ XP_FreeRoom o; objectloop (o ofclass BlankRoom) if (o.used == false) return o; return 0; ];
[ XP_FreeObj  o; objectloop (o ofclass BlankObject) if (o.used == false) return o; return 0; ];

! --- exit linking (both ways) ---
[ XP_LinkExits fromR toR code;
   switch (code) {
      1: fromR.n_to = toR; toR.s_to = fromR;
      2: fromR.s_to = toR; toR.n_to = fromR;
      3: fromR.e_to = toR; toR.w_to = fromR;
      4: fromR.w_to = toR; toR.e_to = fromR;
      5: fromR.u_to = toR; toR.d_to = fromR;
      6: fromR.d_to = toR; toR.u_to = fromR;
   }
];

! --- find a room by its typed name (for xlinkn / graph replay) ---
! The host sets XP_root to its start room; the token "origin" resolves to it.
#Ifndef XP_root; Global XP_root = 0; #Endif;
[ XP_WordIsOrigin wx ad ln;
   ad = WordAddress(wx); ln = WordLength(wx);
   if (ln ~= 6) rfalse;
   return (ad->0 == 'o' && ad->1 == 'r' && ad->2 == 'i' && ad->3 == 'g' && ad->4 == 'i' && ad->5 == 'n');
];
[ XP_FindRoom wx o;
   if (XP_WordIsOrigin(wx)) return XP_root;
   objectloop (o ofclass BlankRoom)
      if (o.used && XP_WordEq(wx, XP_RNm(o))) return o;
   return 0;
];

! --- meta-verbs the engine drives ---
! xroom <dir> <name>  : claim a blank room <dir> of the player's room, name it, link both ways.
[ XroomSub  newR code;
   code = XP_DirCode(2);
   if (code == 0) "xroom bad-direction";
   newR = XP_FreeRoom();
   if (newR == 0) "xroom no-free-room";
   XP_CopyWord(3, XP_RNm(newR), XP_NBUF);
   newR.used = true;
   XP_LinkExits(location, newR, code);
   XP_lastroom = newR;
   "xroom ok";
];
! xdesc <words...> : set the description of the most-recently-created room.
[ XrdescSub;
   if (XP_lastroom == 0) "xdesc no-room";
   XP_CopyTail(2, XP_RDs(XP_lastroom), XP_RDBUF);
   "xdesc ok";
];
! xobj <flag> <name> : claim a blank object into the last room; flag 1 = takeable.
[ XobjSub  newO;
   if (XP_lastroom == 0) "xobj no-room";
   newO = XP_FreeObj();
   if (newO == 0) "xobj no-free-obj";
   newO.takeable = XP_TakeFlag(2);
   XP_CopyWord(3, XP_ONm(newO), XP_NBUF);
   newO.used = true;
   move newO to XP_lastroom;
   XP_lastobj = newO;
   "xobj ok";
];
! xodesc <words...> : set the description of the most-recently-created object.
[ XodescSub;
   if (XP_lastobj == 0) "xodesc no-obj";
   XP_CopyTail(2, XP_ODs(XP_lastobj), XP_ODBUF);
   "xodesc ok";
];
! xnew <name> : claim + name a blank room with NO link (for graph replay).
[ XnewSub  newR;
   newR = XP_FreeRoom();
   if (newR == 0) "xnew no-free-room";
   XP_CopyWord(2, XP_RNm(newR), XP_NBUF);
   newR.used = true;
   XP_lastroom = newR;
   "xnew ok";
];
! xlinkn <fromname> <dir> <toname> : link two existing named rooms both ways.
[ XlinknSub  f code t;
   f = XP_FindRoom(2);
   code = XP_DirCode(3);
   t = XP_FindRoom(4);
   if (f == 0 || t == 0 || code == 0) "xlinkn miss";
   XP_LinkExits(f, t, code);
   "xlinkn ok";
];

Verb 'xroom'  * topic -> Xroom;
Verb 'xdesc'  * topic -> Xrdesc;
Verb 'xobj'   * topic -> Xobj;
Verb 'xodesc' * topic -> Xodesc;
Verb 'xnew'   * topic -> Xnew;
Verb 'xlinkn' * topic -> Xlinkn;
`;

writeFileSync(new URL('./expanse.h', import.meta.url), h);
console.log(`wrote expanse.h (${ROOMS} rooms, ${OBJS} objects)`);
